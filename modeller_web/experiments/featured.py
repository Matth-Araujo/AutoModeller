def format_structure(item, is_pt=True):
    """Formata um item do catálogo para consumo no frontend/template."""
    pdb_file = item["pdb_file"]
    return {
        "id": item["id"],
        "name": item["name_pt"] if is_pt else item["name_en"],
        "organism": item["organism"],
        "badge": item["badge_pt"] if is_pt else item["badge_en"],
        "badgeClass": item["badge_class"],
        "desc": item["desc_pt"] if is_pt else item["desc_en"],
        "type": item["type_pt"] if is_pt else item["type_en"],
        "metric": item["metric_pt"] if is_pt else item["metric_en"],
        "pdbUrl": f"/static/pdb/{pdb_file}",
        "fallbackPdbUrl": f"https://files.rcsb.org/download/{item['id']}.pdb" if item["rcsb_url"] else None,
        "rcsbUrl": item["rcsb_url"],
        "isSample": item.get("is_sample", False),
    }


def get_daily_featured_structures(target_date=None, count=4, seed_offset=0, is_pt=True):
    """
    Retorna uma lista determinística de 'count' estruturas baseada na data do dia.
    
    A semente é gerada no formato YYYYMMDD + offset.
    - Todos os usuários no mesmo dia veem as mesmas 4 estruturas.
    - A cada virada de dia (00:00), 4 estruturas diferentes são sorteadas.
    - O seed_offset permite 'Sortear Outras' sob demanda (ex: botão shuffle).
    """
    if target_date is None:
        target_date = timezone.localdate()

    date_seed = (target_date.year * 10000) + (target_date.month * 100) + target_date.day
    seed = date_seed + seed_offset

    rng = random.Random(seed)
    selected_raw = rng.sample(FEATURED_CATALOG, min(count, len(FEATURED_CATALOG)))

    return [format_structure(st, is_pt=is_pt) for st in selected_raw]
